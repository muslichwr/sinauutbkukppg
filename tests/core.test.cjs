const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const Core = require('../assets/core.js');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync('data/bank.bundle.js', 'utf8'), context);
const pack = JSON.parse(JSON.stringify(context.window.UKPPPG_BANK.packages[0]));
const pg = {type:'PG', options:['a','b','c'],key:'B'};
const cat = {type:'Kategori', options:['a','b','c'],key:['T','F','T']};
const mc = {type:'MCMA', options:['a','b','c','d'],key:['A','C']};

test('grading rejects partial categories, duplicate/extra MCMA, invalid PG', () => {
  assert.equal(Core.correct(pg,'B'),true);
  assert.equal(Core.answered(pg,'Z'),false);
  assert.equal(Core.correct(cat,['T','F']),false);
  assert.equal(Core.answered(cat,['T','','T']),false);
  assert.equal(Core.correct(cat,['T','F','T']),true);
  assert.equal(Core.correct(mc,['C','A']),true);
  assert.equal(Core.correct(mc,['A','A']),false);
  assert.equal(Core.correct(mc,['A','B','C']),false);
  assert.equal(Core.correct(mc,['A']),false);
});
test('new full attempt snapshots questions and preserves stable IDs', () => {
  const a=Core.createAttempt(pack,150,1000,'one');
  assert.equal(a.questions.length,80);
  assert.equal(a.questions[0].uid,'p1-001');
  assert.equal(a.deadline,9001000);
  const original=pack.questions[0].stem;
  pack.questions[0].stem='changed';
  assert.equal(a.questions[0].stem,original);
  pack.questions[0].stem=original;
  assert.throws(()=>Core.createAttempt({...pack,questions:pack.questions.slice(0,79)},150,0,'bad'));
  assert.throws(()=>Core.createAttempt(pack,-1,0,'bad'));
});
test('deadline is absolute, timeout freezes responses and hides review until finished',()=>{
  const a=Core.createAttempt(pack,1,1000,'time');
  assert.equal(Core.review(a,0),null);
  assert.equal(Core.remaining(a,11000),50000);
  assert.equal(Core.expire(a,60999),false);
  assert.equal(Core.expire(a,61000),true);
  assert.equal(a.status,'completed');
  assert.equal(a.completedAt,61000);
  assert.equal(a.finishReason,'timeout');
  assert.ok(Core.review(a,0));
  assert.equal(Core.setAnswer(a,a.questions[0].uid,'B',62000),false);
});
test('results count correct items, blanks and all three breakdowns; retry keeps history',()=>{
  const a=Core.createAttempt(pack,0,100,'score');
  Core.setAnswer(a,'p1-001','B',200);
  Core.setAnswer(a,'p1-002',a.questions[1].key,200);
  Core.setAnswer(a,'p1-003','A',200);
  Core.finish(a,'manual',300);
  const r=Core.summarize(a);
  assert.equal(r.correct,2);
  assert.equal(r.unanswered,77);
  assert.equal(r.total,80);
  assert.equal(r.sections.PCK.total,50);
  assert.equal(r.sections.PU.total,30);
  assert.equal(r.types.PG.total,40);
  assert.equal(r.types.Kategori.total,20);
  assert.equal(r.types.MCMA.total,20);
  assert.equal(Object.keys(r.codes).length,17);
  const history=[a,Core.createAttempt(pack,0,400,'retry')];
  assert.equal(history[0].answers['p1-001'],'B');
  assert.deepEqual(history[1].answers,{});
  assert.equal(history[1].deadline,null);
});
test('legacy import preserves original order/answers and remains an archive',()=>{
  const legacy={pool:[1,4], answers:{1:'B',4:['T','F','T']}, flagged:{4:true},idx:1,done:false,mode:'home'};
  const a=Core.importLegacy(legacy,context.window.UKPPPG_BANK.legacyQuestions,100);
  assert.equal(a.status,'archived');
  assert.equal(a.bankVersion,'prototipe-v0');
  assert.equal(a.questions.length,2);
  assert.deepEqual(a.answers['legacy-1'],'B');
  assert.deepEqual(a.answers['legacy-4'],['T','F','T']);
  assert.equal(a.questions[1].key.join(''),'TFT');
  assert.equal(Core.importLegacy({pool:[999]},[],100),null);
});
test('two package sessions remain independent and malformed databases are rejected',()=>{
  const a=Core.createAttempt(pack,0,0,'p1');
  const second=JSON.parse(JSON.stringify(pack)); second.id=2; second.title='Test-only Paket 2';
  const b=Core.createAttempt(second,0,0,'p2');
  Core.setAnswer(a,'p1-001','B',100);
  assert.equal(b.answers['p1-001'],undefined);
  const db={schemaVersion:2,revision:0,attempts:[a,b],legacyImported:false};
  assert.equal(Core.validDatabase(db),true);
  assert.equal(Core.validDatabase({schemaVersion:2,attempts:[{}]}),false);
  const badAnswer=JSON.parse(JSON.stringify(db));
  badAnswer.attempts[0].answers['p1-002']='A';
  assert.equal(Core.validDatabase(badAnswer),false,'MCMA strings would crash the input handler');
  const badReasons=JSON.parse(JSON.stringify(db));
  badReasons.attempts[0].questions[0].explanations={bad:true};
  assert.equal(Core.validDatabase(badReasons),false,'review needs an array of explanations');
});
